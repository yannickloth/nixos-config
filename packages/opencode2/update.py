#!/usr/bin/env nix-shell
#! nix-shell -i python3 -p python3 curl
"""Regenerates the pin in ./default.nix: the version and the two per-arch
hashes between the "generated by update.py" markers.

Upstream ships the v2 CLI only on npm, and its release API
(https://opencode.ai/update/api/latest/cli/npm) carries the version but no
hashes for the registry tarballs — so each platform tarball is downloaded and
hashed with `nix store prefetch-file` (~100 MiB per platform, kept in the store
afterwards). The desktop package needs none of that: its own API publishes the
sha256 (see packages/opencode-desktop/update.py).

Run it from inside this checkout (`./update.py`, or
`packages/opencode2/update.py` from the repository root), or let nix-update do
it: `nix-update opencode --flake --use-update-script`.
"""
import json
import pathlib
import subprocess
import sys

API = "https://opencode.ai/update/api/latest/cli/npm"

# nix platform -> npm platform package (at sign) suffix.
PLATFORMS = [
    ("x86_64-linux", "cli-linux-x64"),
    ("aarch64-linux", "cli-linux-arm64"),
]

def repo_root():
    """The nixos-config checkout this package lives in.

    nix-update runs `passthru.updateScript` from the repository root, and from the
    script's own store path where __file__ is just a /nix/store hash — the package
    directory cannot be derived from it. So resolve the layout from the working
    directory instead, walking up to the shared helper in packages/tools.
    """
    for candidate in (pathlib.Path.cwd(), *pathlib.Path.cwd().parents):
        if (candidate / "packages" / "tools" / "pin_block.py").is_file():
            return candidate
    raise SystemExit(
        "update.py: no packages/tools/pin_block.py above the working directory; "
        "run from the nixos-config checkout (nix-update does)"
    )


ROOT = repo_root()
TARGET = ROOT / "packages/opencode2/default.nix"

# Keep __pycache__ out of the tree when importing the shared helper.
sys.dont_write_bytecode = True
sys.path.insert(0, str(ROOT / "packages/tools"))
from pin_block import rewrite  # noqa: E402  (path set above)


def curl_json(url):
    out = subprocess.run(["curl", "-fsSL", url], check=True, capture_output=True, text=True)
    return json.loads(out.stdout)


def prefetch(url):
    """SRI sha256 of a file, via the nix store (downloads it if not cached)."""
    out = subprocess.run(
        ["nix", "store", "prefetch-file", "--json", "--hash-type", "sha256", url],
        check=True,
        capture_output=True,
        text=True,
    )
    return json.loads(out.stdout)["hash"]


version = curl_json(API)["version"]
print(f"opencode CLI: upstream version {version}")

entries = []
for platform, suffix in PLATFORMS:
    package = f"@opencode/{suffix}"
    url = f"https://registry.npmjs.org/{package}/-/{suffix}-{version}.tgz"
    hash = prefetch(url)
    print(f"  {platform}: {hash}")
    entries.append((platform, package, suffix, hash))

block = (
    "\n".join(
        [
            f'  version = "{version}";',
            "",
            "  perArch = {",
            *[
                "\n".join(
                    [
                        f"    {platform} = {{",
                        # ${version} is interpolated by default.nix, so only the
                        # version constant above has to change.
                        f'      url = "https://registry.npmjs.org/{package}/-/{suffix}-${{version}}.tgz";',
                        f'      hash = "{hash}";',
                        "    };",
                    ]
                )
                for platform, package, suffix, hash in entries
            ],
            "  };",
        ]
    )
    + "\n"
)

rewrite(TARGET, block)
