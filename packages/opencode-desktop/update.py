#!/usr/bin/env nix-shell
#! nix-shell -i python3 -p python3 curl
"""Regenerates the pin in ./default.nix: the version and the two per-arch
hashes between the "generated by update.py" markers.

Unlike the CLI (packages/opencode2/update.py), upstream's release API for the
desktop build (https://opencode.ai/update/api/latest/desktop) publishes the URL
*and* the sha256 of every platform installer, so this needs no downloads and no
prefetching: version, URLs and hashes all come from one JSON document.

Run it from inside this checkout (`./update.py`, or
`packages/opencode-desktop/update.py` from the repository root), or let
nix-update do it: `nix-update opencode-desktop --flake --use-update-script`.
"""
import base64
import json
import pathlib
import subprocess
import sys

API = "https://opencode.ai/update/api/latest/desktop"

# nix platform -> upstream AppImage name.
PLATFORMS = [
    ("x86_64-linux", "opencode-desktop-linux-x86_64.AppImage"),
    ("aarch64-linux", "opencode-desktop-linux-arm64.AppImage"),
]

def repo_root():
    """The nixos-config checkout this package lives in.

    nix-update runs `passthru.updateScript` from the repository root, and from the
    script's own store path where __file__ is just a /nix/store hash — the package
    directory cannot be derived from it. So resolve the layout from the working
    directory instead, walking up to the shared helper in packages/tools.
    """
    for candidate in (pathlib.Path.cwd(), *pathlib.Path.cwd().parents):
        if (candidate / "packages" / "tools" / "pin_block.py").is_file():
            return candidate
    raise SystemExit(
        "update.py: no packages/tools/pin_block.py above the working directory; "
        "run from the nixos-config checkout (nix-update does)"
    )


ROOT = repo_root()
TARGET = ROOT / "packages/opencode-desktop/default.nix"

# Keep __pycache__ out of the tree when importing the shared helper.
sys.dont_write_bytecode = True
sys.path.insert(0, str(ROOT / "packages/tools"))
from pin_block import rewrite  # noqa: E402  (path set above)


def curl_json(url):
    out = subprocess.run(["curl", "-fsSL", url], check=True, capture_output=True, text=True)
    return json.loads(out.stdout)


artifacts = curl_json(API)["artifacts"][0]
version = artifacts["version"]
files = artifacts["metadata"]["files"]
print(f"opencode Desktop: upstream version {version}")

entries = []
for platform, name in PLATFORMS:
    meta = files.get(name)
    if meta is None:
        sys.exit(f"update.py: {name} missing from the release API")
    expected = f"https://opencode.ai/files/bin/{version}/{name}"
    if meta["url"] != expected:
        # default.nix builds the URL from the version, so an upstream layout
        # change has to be reflected there by hand.
        sys.exit(f"update.py: unexpected url {meta['url']} (expected {expected})")
    hash = "sha256-" + base64.b64encode(bytes.fromhex(meta["sha256"])).decode()
    print(f"  {platform}: {hash}")
    entries.append((platform, name, hash))

block = (
    "\n".join(
        [
            f'  version = "{version}";',
            "",
            "  perArch = {",
            *[
                "\n".join(
                    [
                        f"    {platform} = {{",
                        # ${version} is interpolated by default.nix, so only the
                        # version constant above has to change.
                        f'      url = "https://opencode.ai/files/bin/${{version}}/{name}";',
                        f'      hash = "{hash}";',
                        "    };",
                    ]
                )
                for platform, name, hash in entries
            ],
            "  };",
        ]
    )
    + "\n"
)

rewrite(TARGET, block)
